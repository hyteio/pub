#!/usr/bin/env bash
# Regenerate the documentation pages that come from pub itself:
#   docs/src/reference/settings.md   from `pub config settings --markdown`
#   docs/src/reference/commands.md   from every command's --help
#
#   docs/generate.sh            # with the default build (all modules and formats)
#   PUB=path/to/pub docs/generate.sh
#
# CI runs this and fails if the result differs from what's committed.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
root="$(dirname "$here")"
ref="$here/src/reference"
if [ -z "${PUB:-}" ]; then
  cargo build -q -p pub-cli --manifest-path "$root/Cargo.toml"
  PUB="$root/target/debug/pub"
fi
# A home with no configuration, so the output doesn't depend on ~/.pub.
home="$(mktemp -d)"
trap 'rm -rf "$home"' EXIT
export PUB_HOME="$home"

{
  echo "# Settings"
  echo
  echo "<!-- Generated by docs/generate.sh from \`pub config settings --markdown\`; don't edit by hand. -->"
  echo
  echo "Every setting pub understands. Set them in a config file, in a URL query, or with"
  echo "\`-O key=value\` (see [Configuration](../configuration.md)). Types: a *duration* is \`10s\`,"
  echo "\`500ms\`, \`2m\` or \`1h\` (\`0\` = none); a *size* is \`65536\`, \`256k\`, \`4m\` or \`1g\`."
  echo
  "$PUB" config settings --markdown
} > "$ref/settings.md"

help_page() { # title, command words...
  local title="$1"; shift
  echo "## $title"
  echo
  echo '```text'
  "$PUB" "$@" --help
  echo '```'
  echo
}

{
  echo "# Commands"
  echo
  echo "<!-- Generated by docs/generate.sh from \`pub ... --help\`; don't edit by hand. -->"
  echo
  echo '```text'
  "$PUB" --help
  echo '```'
  echo
  for cmd in send recv browse unsub move ping modules formats; do
    help_page "pub $cmd" "$cmd"
  done
  for sub in list create delete; do
    help_page "pub dest $sub" dest "$sub"
  done
  for sub in list show add remove resolve; do
    help_page "pub alias $sub" alias "$sub"
  done
  for sub in list path init check settings headers; do
    help_page "pub config $sub" config "$sub"
  done
} > "$ref/commands.md"

echo "wrote $ref/settings.md and $ref/commands.md"
